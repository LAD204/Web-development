<?php

class MayTinh {
    public function tinhCong($a, $b) {
        return $a + $b;
       
    }
    public function tinhTru($a, $b) {
        return $a - $b;
       
    }
    public function tinhNhan($a, $b) {
        return $a * $b;
       
    }
    public function tinhChia($a, $b) {
        return $a / $b;
       
    }
    public function tinhChiaLayDu($a, $b) {
        return $a % $b;
       
    }
}